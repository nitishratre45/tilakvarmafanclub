/* Match Centre: Upcoming Match is the default tab; scorecards load on demand. */
(() => {
  "use strict";
  const $ = (id) => document.getElementById(id);
  const esc = (v) =>
    String(v ?? "—").replace(
      /[&<>"']/g,
      (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c],
    );
  const state = { matches: [], format: "All", query: "" };
  const fmtLabel = (v) =>
    ({
      T20I: "T20 International",
      T20: "T20 / IPL",
      ODI: "One Day International",
      "List A": "List A / domestic ODI",
      Test: "Test",
      "First-class": "First-class / multi-day",
    })[v] ||
    v ||
    "Cricket";
  const dateLabel = (v) => {
    if (!v) return "Date unavailable";
    const d = new Date(v + "T12:00:00Z");
    return Number.isNaN(d.getTime())
      ? v
      : d.toLocaleDateString("en-IN", {
          day: "numeric",
          month: "short",
          year: "numeric",
          timeZone: "UTC",
        });
  };
  function setTab(tab) {
    document.querySelectorAll("[data-match-tab]").forEach((b) => {
      const active = b.dataset.matchTab === tab;
      b.classList.toggle("is-active", active);
      b.setAttribute("aria-selected", String(active));
    });
    $("match-upcoming-panel").hidden = tab !== "upcoming";
    $("match-complete-panel").hidden = tab !== "complete";
    if (tab === "complete") renderMatches();
  }
  document
    .querySelectorAll("[data-match-tab]")
    .forEach((b) => b.addEventListener("click", () => setTab(b.dataset.matchTab)));

  async function loadUpcoming() {
    const host = $("upcoming-matches-list");
    try {
      // Snapshot is generated by the existing News/newsjson.json fixture pipeline.
      const response = await fetch(
        "/matches/upcoming-fixtures-refresh.json?v=20261014-match-centre1",
        { cache: "no-store" },
      );
      if (!response.ok) throw new Error("Fixture JSON unavailable");
      const payload = await response.json();
      const fixtures = (Array.isArray(payload.fixtures) ? payload.fixtures : [])
        .filter((f) => {
          const start = Date.parse(
            String(f.date || "") + "T" + String(f.time || "19:00") + ":00+05:30",
          );
          return Number.isFinite(start) && start + 4 * 60 * 60 * 1000 > Date.now();
        })
        .sort((a, b) => String(a.date).localeCompare(String(b.date)));
      if (!fixtures.length) {
        host.innerHTML =
          '<div class="match-empty"><strong>No upcoming fixtures found</strong><span>News JSON se next confirmed fixture update hote hi yahan dikhega.</span></div>';
      } else {
        host.innerHTML = fixtures
          .map((f) => {
            const link = f.newsUrl || f.source || "/news/";
            const target = /^https?:\/\//i.test(link) ? ' target="_blank"' : "";
            return (
              '<article class="upcoming-match-card"><div class="upcoming-match-topline"><span class="upcoming-match-date">' +
              esc(f.label || dateLabel(f.date)) +
              '</span><span class="match-live-tag">UPCOMING</span></div><div class="upcoming-match-teams"><span>India</span><span class="versus">VS</span><span>' +
              esc(f.opponent || "Opponent TBA") +
              '</span></div><div class="upcoming-match-meta"><span>' +
              esc(f.match || "International match") +
              "</span><span>⌖ " +
              esc(f.venue || "Venue TBA") +
              "</span><span>" +
              esc(f.time || "Time TBA") +
              ' IST</span></div><a class="match-details-link" href="' +
              esc(link) +
              '"' +
              target +
              ' rel="noopener">Match details <span aria-hidden="true">↗</span></a></article>'
            );
          })
          .join("");
      }
      const note = $("upcoming-matches-updated");
      if (note)
        note.textContent =
          "Upcoming fixtures from News JSON · checked " +
          (payload.checkedAt
            ? new Date(payload.checkedAt).toLocaleString("en-IN")
            : "latest saved snapshot") +
          ".";
      const announcement = $("upcoming-team-announcement-link");
      if (announcement && fixtures[0]) announcement.href = fixtures[0].newsUrl || "/news/";
    } catch (error) {
      host.innerHTML =
        '<div class="match-empty"><strong>Upcoming fixtures could not load</strong><span>Saved News JSON fixture snapshot dobara try karein.</span></div>';
      console.error("Match Centre upcoming fixtures:", error);
    }
  }
  async function loadScorecards() {
    const host = $("complete-matches-list");
    try {
      const response = await fetch("/matches/scorecards/index.json?v=20261014-scorecards1", {
        cache: "no-store",
      });
      if (!response.ok) throw new Error("Scorecard index not published yet");
      const payload = await response.json();
      state.matches = Array.isArray(payload.matches) ? payload.matches : [];
      $("scorecard-count").textContent = (payload.matchCount || state.matches.length) + " matches";
      $("scorecard-updated").textContent = payload.updatedAt
        ? "Data updated " + new Date(payload.updatedAt).toLocaleString("en-IN") + " · Cricsheet"
        : "Cricsheet match archive";
      $("scorecard-source-note").textContent =
        payload.coverageNote || "Only verified available scorecards are shown.";
      renderMatches();
    } catch (error) {
      host.innerHTML =
        '<div class="match-empty"><strong>Scorecards are being prepared</strong><span>First data refresh ke baad complete matches yahan appear honge. Empty/fake scorecards nahi dikhaye jayenge.</span></div>';
      console.error("Match Centre scorecards:", error);
    }
  }
  function renderMatches() {
    const host = $("complete-matches-list");
    if (!host) return;
    const q = state.query.trim().toLowerCase();
    const rows = state.matches.filter(
      (m) =>
        (state.format === "All" || m.format === state.format) &&
        (!q ||
          [m.team, m.opposition, m.venue, m.event, m.date, m.format, m.result]
            .join(" ")
            .toLowerCase()
            .includes(q)),
    );
    if (!rows.length) {
      host.innerHTML =
        '<div class="match-empty"><strong>No matching scorecards</strong><span>Search ya format filter badal kar dekhein.</span></div>';
      return;
    }
    host.innerHTML = rows
      .map(
        (m) =>
          '<article class="complete-match-card" data-match-id="' +
          esc(m.matchId) +
          '"><div class="complete-match-topline"><span>' +
          esc(dateLabel(m.date)) +
          '</span><span class="match-format-pill">' +
          esc(fmtLabel(m.format)) +
          '</span></div><div class="complete-match-teams"><span>' +
          esc(m.team || "Tilak team") +
          "</span><b>VS</b><span>" +
          esc(m.opposition || "Opponent") +
          '</span></div><div class="complete-match-venue">⌖ ' +
          esc(m.venue || "Venue unavailable") +
          '</div><div class="complete-match-result">' +
          esc(m.result || "Result unavailable") +
          '</div><div class="complete-match-bottom"><span>Tilak: ' +
          Number(m.playerRuns || 0) +
          " runs · " +
          Number(m.inningsCount || 0) +
          ' innings</span><button type="button" class="scorecard-open" data-scorecard="' +
          esc(m.matchId) +
          '">Full scorecard ↗</button></div><div class="scorecard-detail" id="scorecard-detail-' +
          esc(m.matchId) +
          '" hidden></div></article>',
      )
      .join("");
  }
  function battingTable(rows) {
    return (
      '<div class="scorecard-table-scroll"><table class="scorecard-table"><thead><tr><th>Batter</th><th>Dismissal</th><th>R</th><th>B</th><th>4s</th><th>6s</th><th>SR</th></tr></thead><tbody>' +
      (rows || [])
        .map(
          (r) =>
            "<tr><td>" +
            esc(r.batter) +
            "</td><td>" +
            esc(r.dismissal || (r.notOut ? "not out" : "—")) +
            "</td><td><b>" +
            esc(r.runs) +
            "</b></td><td>" +
            esc(r.balls) +
            "</td><td>" +
            esc(r.fours) +
            "</td><td>" +
            esc(r.sixes) +
            "</td><td>" +
            esc(r.strikeRate) +
            "</td></tr>",
        )
        .join("") +
      "</tbody></table></div>"
    );
  }
  function bowlingTable(rows) {
    return (
      '<div class="scorecard-table-scroll"><table class="scorecard-table"><thead><tr><th>Bowler</th><th>O</th><th>M</th><th>R</th><th>W</th><th>Eco</th></tr></thead><tbody>' +
      (rows || [])
        .map(
          (r) =>
            "<tr><td>" +
            esc(r.bowler) +
            "</td><td>" +
            esc(r.overs) +
            "</td><td>" +
            esc(r.maidens) +
            "</td><td>" +
            esc(r.runs) +
            "</td><td><b>" +
            esc(r.wickets) +
            "</b></td><td>" +
            esc(r.economy) +
            "</td></tr>",
        )
        .join("") +
      "</tbody></table></div>"
    );
  }
  function renderScorecard(data, host) {
    const inningsHtml = (data.innings || [])
      .map((inn) => {
        const extras =
          Object.entries(inn.extrasBreakdown || {})
            .map(([k, v]) => k + ": " + v)
            .join(" · ") || "None";
        const fow = (inn.fallOfWickets || [])
          .map((x) => x.score + "/" + x.wicket + " (" + x.batter + ", " + x.over + ")")
          .join(" · ");
        const deliveries = (inn.deliveries || [])
          .map((b) => {
            const run = b.totalRuns === 0 ? "·" : "+" + b.totalRuns;
            const wicket = (b.wickets || []).length
              ? " WICKET: " + b.wickets.map((w) => w.player + " (" + w.kind + ")").join(", ")
              : "";
            return (
              '<span class="' +
              ((b.wickets || []).length ? "delivery-wicket" : "") +
              '"><b>' +
              b.over +
              "." +
              b.ball +
              "</b> " +
              esc(b.bowler) +
              " to " +
              esc(b.batter) +
              " — " +
              run +
              esc(wicket) +
              "</span>"
            );
          })
          .join("");
        return (
          '<section class="scorecard-innings"><div class="scorecard-innings-heading"><div><small>INNINGS ' +
          inn.number +
          "</small><h4>" +
          esc(inn.team) +
          "</h4></div><strong>" +
          esc(inn.runs) +
          "/" +
          esc(inn.wickets) +
          " <small>(" +
          esc(inn.overs) +
          ' ov)</small></strong></div><p class="scorecard-extras"><b>Extras ' +
          esc(inn.extras) +
          ":</b> " +
          esc(extras) +
          "</p><h5>Batting</h5>" +
          battingTable(inn.batting) +
          "<h5>Bowling</h5>" +
          bowlingTable(inn.bowling) +
          (fow ? '<p class="scorecard-fow"><b>Fall of wickets:</b> ' + esc(fow) + "</p>" : "") +
          '<details class="scorecard-deliveries"><summary>Ball-by-ball (' +
          (inn.deliveries || []).length +
          ' deliveries)</summary><div class="delivery-list">' +
          (deliveries || "Delivery detail unavailable.") +
          "</div></details></section>"
        );
      })
      .join("");
    host.innerHTML =
      '<div class="scorecard-detail-head"><div><span class="eyebrow">VERIFIED MATCH DATA</span><h3>' +
      esc(data.team) +
      " <em>VS</em> " +
      esc(data.opposition) +
      "</h3><p>" +
      esc(dateLabel(data.date)) +
      " · " +
      esc(data.venue) +
      " · " +
      esc(fmtLabel(data.format)) +
      '</p></div><button type="button" class="scorecard-close">Close ×</button></div><p class="scorecard-result">' +
      esc(data.result) +
      "</p>" +
      (inningsHtml || "<p>Innings data unavailable.</p>") +
      '<p class="scorecard-attribution">Source: <a href="' +
      esc(data.source || "https://cricsheet.org/") +
      '" target="_blank" rel="noopener">Cricsheet</a> · ' +
      esc(data.attribution || "Verified public match data") +
      "</p>";
    host.hidden = false;
  }
  $("match-format-filter")?.addEventListener("change", (e) => {
    state.format = e.target.value;
    renderMatches();
  });
  $("match-search")?.addEventListener("input", (e) => {
    state.query = e.target.value;
    renderMatches();
  });
  $("complete-matches-list")?.addEventListener("click", async (event) => {
    const button = event.target.closest("[data-scorecard]");
    if (button) {
      const id = button.dataset.scorecard,
        detail = $("scorecard-detail-" + id);
      if (!detail) return;
      if (!detail.hidden) {
        detail.hidden = true;
        button.textContent = "Full scorecard ↗";
        return;
      }
      button.disabled = true;
      button.textContent = "Loading scorecard…";
      try {
        const response = await fetch(
          "/matches/scorecards/data/" + encodeURIComponent(id) + ".json",
          { cache: "force-cache" },
        );
        if (!response.ok) throw new Error("Scorecard file not found");
        renderScorecard(await response.json(), detail);
        button.textContent = "Hide scorecard ↑";
        if (!window.matchMedia("(prefers-reduced-motion: reduce)").matches)
          detail.scrollIntoView({ behavior: "smooth", block: "start" });
      } catch (error) {
        detail.hidden = false;
        detail.innerHTML =
          '<p class="match-empty">Scorecard file could not load. Daily refresh complete hone ke baad retry karein.</p>';
        button.textContent = "Retry scorecard";
        console.error(error);
      } finally {
        button.disabled = false;
      }
      return;
    }
    const close = event.target.closest(".scorecard-close");
    if (close) {
      const detail = close.closest(".scorecard-detail");
      if (detail) detail.hidden = true;
    }
  });
  loadUpcoming();
  loadScorecards();
  setTab("upcoming");
})();
