/* Upcoming fixtures module; Complete Match lives in /matches/complete/. */
(() => {
  "use strict";
  const $ = (id) => document.getElementById(id);
  const esc = (v) =>
    String(v ?? "—").replace(
      /[&<>"']/g,
      (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c],
    );
  const dateLabel = (v) => {
    if (!v) return "Date unavailable";
    const d = new Date(v + "T12:00:00Z");
    return Number.isNaN(d.getTime())
      ? v
      : d.toLocaleDateString("en-IN", {
          day: "numeric",
          month: "short",
          year: "numeric",
          timeZone: "UTC",
        });
  };
  async function loadUpcoming() {
    const host = $("upcoming-matches-list");
    try {
      // Snapshot is generated by the existing News/newsjson.json fixture pipeline.
      const response = await fetch(
        "/matches/upcoming-fixtures-refresh.json?v=20261014-match-centre1",
        { cache: "no-store" },
      );
      if (!response.ok) throw new Error("Fixture JSON unavailable");
      const payload = await response.json();
      const fixtures = (Array.isArray(payload.fixtures) ? payload.fixtures : [])
        .filter((f) => {
          const start = Date.parse(
            String(f.date || "") + "T" + String(f.time || "19:00") + ":00+05:30",
          );
          return Number.isFinite(start) && start + 4 * 60 * 60 * 1000 > Date.now();
        })
        .sort((a, b) => String(a.date).localeCompare(String(b.date)));
      if (!fixtures.length) {
        host.innerHTML =
          '<div class="match-empty"><strong>No upcoming fixtures found</strong><span>News JSON se next confirmed fixture update hote hi yahan dikhega.</span></div>';
      } else {
        host.innerHTML = fixtures
          .map((f) => {
            const link = f.newsUrl || f.source || "/news/";
            const target = /^https?:\/\//i.test(link) ? ' target="_blank"' : "";
            return (
              '<article class="upcoming-match-card"><div class="upcoming-match-topline"><span class="upcoming-match-date">' +
              esc(f.label || dateLabel(f.date)) +
              '</span><span class="match-live-tag">UPCOMING</span></div><div class="upcoming-match-teams"><span>India</span><span class="versus">VS</span><span>' +
              esc(f.opponent || "Opponent TBA") +
              '</span></div><div class="upcoming-match-meta"><span>' +
              esc(f.match || "International match") +
              "</span><span>⌖ " +
              esc(f.venue || "Venue TBA") +
              "</span><span>" +
              esc(f.time || "Time TBA") +
              ' IST</span></div><a class="match-details-link" href="' +
              esc(link) +
              '"' +
              target +
              ' rel="noopener">Match details <span aria-hidden="true">↗</span></a></article>'
            );
          })
          .join("");
      }
      const note = $("upcoming-matches-updated");
      if (note)
        note.textContent =
          "Upcoming fixtures from News JSON · checked " +
          (payload.checkedAt
            ? new Date(payload.checkedAt).toLocaleString("en-IN")
            : "latest saved snapshot") +
          ".";
      const announcement = $("upcoming-team-announcement-link");
      if (announcement && fixtures[0]) announcement.href = fixtures[0].newsUrl || "/news/";
    } catch (error) {
      host.innerHTML =
        '<div class="match-empty"><strong>Upcoming fixtures could not load</strong><span>Saved News JSON fixture snapshot dobara try karein.</span></div>';
      console.error("Match Centre upcoming fixtures:", error);
    }
  }
  loadUpcoming();
})();
